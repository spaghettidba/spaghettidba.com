"""Generate WordPress-compatible monthly archives from Hugo's content metadata."""

import calendar
import csv
from datetime import datetime, timezone
import io
import json
from pathlib import Path
import re
import subprocess


ROOT = Path(__file__).resolve().parents[1]
ARCHIVES_DIR = ROOT / "content" / "archives"
MARKER = "<!-- Generated by scripts/generate_archives.py; do not edit. -->"


def published_months(rows, now):
    months = set()
    for row in rows:
        path = Path(row["path"])
        if path.is_absolute():
            path = path.relative_to(ROOT)
        if path.parts[:2] != ("content", "posts") or row["draft"] == "true":
            continue
        date = datetime.fromisoformat(row["date"].replace("Z", "+00:00"))
        publish_date = datetime.fromisoformat(row["publishDate"].replace("Z", "+00:00"))
        expiry_date = datetime.fromisoformat(row["expiryDate"].replace("Z", "+00:00"))
        if publish_date > now:
            continue
        if expiry_date.year != 1 and expiry_date <= now:
            continue
        months.add(date.strftime("%Y-%m"))
    return months


def write_archives(months, destination=ARCHIVES_DIR):
    expected = {}
    for month in sorted(months):
        year, number = month.split("-")
        metadata = {
            "title": f"{calendar.month_name[int(number)]} {year}",
            "url": f"/{year}/{number}/",
            "type": "monthly-archive",
            "archive_month": month,
            "date": f"{month}-01T00:00:00Z",
            "outputs": ["HTML"],
        }
        front_matter = "\n".join(
            f"{key}: {json.dumps(value)}" for key, value in metadata.items()
        )
        expected[destination / month / "_index.md"] = (
            f"---\n{front_matter}\n---\n\n{MARKER}\n"
        )

    for path in expected:
        if path.exists() and MARKER not in path.read_text(encoding="utf-8"):
            raise ValueError(f"Refusing to overwrite manually maintained archive: {path}")
    for path, content in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8")
    for path in destination.glob("????-??/_index.md"):
        if (
            re.fullmatch(r"\d{4}-\d{2}", path.parent.name)
            and path not in expected
            and MARKER in path.read_text(encoding="utf-8")
        ):
            path.unlink()
            if not any(path.parent.iterdir()):
                path.parent.rmdir()


def main():
    result = subprocess.run(
        ["hugo", "list", "all"],
        cwd=ROOT,
        check=True,
        stdout=subprocess.PIPE,
        encoding="utf-8",
    )
    months = published_months(
        csv.DictReader(io.StringIO(result.stdout)), datetime.now(timezone.utc)
    )
    write_archives(months)
    print(f"Generated {len(months)} monthly archives.")


if __name__ == "__main__":
    main()
